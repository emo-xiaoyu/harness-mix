const assert = require('node:assert/strict');
const { ProtocolCore } = require('../src/main/protocol-core');
const { ShadowMirror } = require('./support/shadow.cjs');
const { CapabilityManager } = require('../src/main/protocol-core/capability-manager');
const { normalizeCapabilities } = require('../src/main/harness-adapter/manifest');

(async () => {
  const core = new ProtocolCore();
  const shadow = new ShadowMirror({ core });
  const thread = { id: 't', cwd: '/test', messages: [{ role: 'assistant', at: 1 }] };
  shadow.threadCreated(thread); shadow.turnStarted(thread, 'test');
  const turn = shadow.lastTurn('t');
  const emit = e => shadow.applyLegacyEvent(thread, e);
  emit({ kind: 'approval', requestId: 'q', method: 'input', title: 'Question' });
  assert.equal(core.interactions.pending('t').length, 1);
  let release, calls = 0;
  const response = core.interactions.respond('t', 'q', {}, async () => { calls++; await new Promise(resolve => { release = resolve; }); });
  await assert.rejects(core.interactions.respond('t', 'q', {}, () => {}), /正在提交/);
  await assert.rejects(core.interactions.respond('other', 'q', {}, () => {}), /过期/);
  release(); await response;
  assert.equal(calls, 1); assert.equal(turn.status, 'running');
  assert.equal(core.interactions.pending('t').length, 0);
  const files = (source, changes, replace = false) => core.dispatch({ threadId: 't', turnId: turn.id,
    type: 'files.updated', payload: { source, changes, replace } });
  files('snapshot', [{ path: 'a', before: 'x', after: 'y', complete: true }]);
  files('native', [{ path: 'a', patch: 'incomplete', complete: false }]);
  assert.equal(core.getItemsForTurn(turn.id).find(i => i.type === 'file_change').source, 'snapshot');
  files('native', [{ path: 'a', before: 'x', after: 'y', complete: true }]);
  files('snapshot', [{ path: 'a', after: 'other' }]);
  const changes = core.getItemsForTurn(turn.id).filter(i => i.type === 'file_change');
  assert.equal(changes.length, 1); assert.equal(changes[0].source, 'native');
  files('git', [{ path: 'b', after: 'z' }]);
  files('git', [], true);
  assert.equal(core.getItemsForTurn(turn.id).filter(i => i.type === 'file_change').length, 1);
  emit({ kind: 'plan', entries: [{ content: 'Inspect', status: 'in_progress' }] });
  emit({ kind: 'plan', entries: [{ content: 'Inspect', status: 'completed' }] });
  assert.equal(core.getItemsForTurn(turn.id).filter(i => i.type === 'plan').length, 1);
  assert.equal(core.getItemsForTurn(turn.id).find(i => i.type === 'plan').entries[0].status, 'completed');
  core.dispatch({ threadId: 't', turnId: turn.id, type: 'turn.completed' });
  files('snapshot', [{ path: 'c', after: 'settled review' }]);
  assert.ok(core.getItemsForTurn(turn.id).some(i => i.path === 'c'));
  const caps = new CapabilityManager();
  caps.register('new-harness', normalizeCapabilities({ fork: true, questions: true, plan: true }));
  caps.require('new-harness', 'session', 'fork');
  assert.throws(() => caps.require('new-harness', 'model', 'selection'));
  const copy = caps.get('new-harness'); copy.session.fork = false;
  assert.equal(caps.get('new-harness').session.fork, true);
  assert.deepEqual(shadow.report().errors, []);
  console.log('core-services: interaction race/ownership, capability negotiation, native precedence, file replacement and plan passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
